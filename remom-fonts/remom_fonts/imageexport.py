"""Save rendered text as pictures the game (or anything else) can use.

* Indexed PNG: 8-bit, the FONTS.LBX VGA palette, index 0 transparent.
  Palette indices are kept exactly, so it drops straight into an LBX/FLIC
  pipeline.
* RGBA PNG: true color, optionally scaled up, for tools and modern UIs.
* MoX picture (.bin): the in-memory layout Create_Picture() builds in ReMoM
  (MoX/src/FLIC_Draw.c): a 16-byte header (width, height, 0xDE0A "decoded"
  marker, frame count 0, loop frame 0) followed by width*height palette
  indices, column by column. Draw it with the game's picture routines, or
  as a target for Print_To_Bitmap().
* C source (.h): the same MoX picture bytes as a const array, in the style
  of ReMoM's Init_Data files.
"""

import re
import struct

import numpy as np
from PIL import Image

FLIC_DECODED = 0xDE0A
FORMATS = {
    "indexed_png": ".png",
    "rgba_png": ".png",
    "mox_picture": ".bin",
    "c_source": ".h",
}


def scaled(indices, scale):
    return np.repeat(np.repeat(indices, scale, axis=0), scale, axis=1) if scale > 1 else indices


def to_rgba(rendered, scale=1, background=None):
    """RGBA array. Index 0 becomes background (r, g, b) or fully transparent."""
    pal = np.array(rendered.palette, dtype=np.uint8)
    idx = scaled(rendered.indices, scale)
    rgba = np.zeros(idx.shape + (4,), dtype=np.uint8)
    rgba[..., :3] = pal[idx]
    rgba[..., 3] = np.where(idx == 0, 0, 255)
    if background is not None:
        clear = idx == 0
        rgba[clear, :3] = background
        rgba[clear, 3] = 255
    return rgba


def indexed_png(rendered, path, scale=1):
    img = Image.fromarray(scaled(rendered.indices, scale), mode="P")
    img.putpalette([c for rgb in rendered.palette for c in rgb])
    img.save(path, transparency=0, optimize=False)


def rgba_png(rendered, path, scale=1, background=None):
    Image.fromarray(to_rgba(rendered, scale, background), mode="RGBA").save(path)


def mox_picture_bytes(rendered):
    h, w = rendered.indices.shape
    if w > 32767 or h > 32767:
        raise ValueError("picture too large for a 16-bit header")
    header = struct.pack("<hhHhh", w, h, FLIC_DECODED, 0, 0) + bytes(6)
    return header + rendered.indices.T.tobytes()  # column-major


def mox_picture(rendered, path):
    with open(path, "wb") as f:
        f.write(mox_picture_bytes(rendered))


def c_identifier(name):
    ident = re.sub(r"\W", "_", name).strip("_") or "text_picture"
    return "_" + ident if ident[0].isdigit() else ident


def c_source(rendered, path, name):
    ident = c_identifier(name)
    data = mox_picture_bytes(rendered)
    h, w = rendered.indices.shape
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    body = ",\n    ".join(rows)
    guard = ident.upper() + "_H"
    text = (f"/* {ident}: {w}x{h} MoX picture (16-byte header + column-major palette indices).\n"
            f"   Generated by remom-fonts Text Studio. Index 0 is transparent. */\n"
            f"#ifndef {guard}\n#define {guard}\n\n#include <stdint.h>\n\n"
            f"#define {ident.upper()}_WIDTH {w}\n#define {ident.upper()}_HEIGHT {h}\n\n"
            f"static const uint8_t {ident}[{len(data)}] =\n{{\n    {body}\n}};\n\n#endif\n")
    with open(path, "w") as f:
        f.write(text)


def save(rendered, fmt, path, scale=1, background=None, name="text_picture"):
    if fmt == "indexed_png":
        indexed_png(rendered, path, scale)
    elif fmt == "rgba_png":
        rgba_png(rendered, path, scale, background)
    elif fmt == "mox_picture":
        mox_picture(rendered, path)
    elif fmt == "c_source":
        c_source(rendered, path, name)
    else:
        raise ValueError(f"unknown format {fmt}")
